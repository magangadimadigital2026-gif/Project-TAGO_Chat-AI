async function main() {
  for (const food of foods) {
    await prisma.food.upsert({
      where: { id: food.id },
      update: {
        name: food.name,
        description: food.description,
        price: food.price,
        category: food.category,
        subcategory: food.subcategory,
        taste: food.taste,
        spicyLevel: food.spicy_level,
        servingType: food.serving_type,
        tags: food.tags,
        isAvailable: food.is_available,
        imageUrl: food.image_url,
        portion: food.portion,
        dietary: food.dietary,
        ingredients: food.ingredients,
      },
      create: {
        id: food.id,
        name: food.name,
        description: food.description,
        price: food.price,
        category: food.category,
        subcategory: food.subcategory,
        taste: food.taste,
        spicyLevel: food.spicy_level,
        servingType: food.serving_type,
        tags: food.tags,
        isAvailable: food.is_available,
        imageUrl: food.image_url,
        portion: food.portion,
        dietary: food.dietary,
        ingredients: food.ingredients,
      },
    });
  }

  console.log(`Berhasil memasukkan ${foods.length} data makanan.`);
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
